function Write-DebugMsg { param([string]$Msg) if ($script:DEBUG) { Write-Host "[DEBUG] $Msg" -ForegroundColor Gray } }
function Write-Err { param([string]$Msg) Write-Host "X $Msg" -ForegroundColor Red }
function Write-Ok { param([string]$Msg) Write-Host "[OK] $Msg" -ForegroundColor Green }

function Get-Today { return (Get-Date -Format "yyyy-MM-dd") }
function Get-FutureDate { param([int]$Days = 7); return (Get-Date).AddDays($Days).ToString("yyyy-MM-dd") }

function Invoke-GH {
    param([string[]]$GhArgs)
    Write-DebugMsg "gh $($GhArgs -join ' ')"
    try {
        $output = & gh @GhArgs 2>&1
        if ($LASTEXITCODE -ne 0) { throw "Exit code $LASTEXITCODE" }
        return $output
    } catch {
        Write-Err "Command failed: gh $($GhArgs -join ' ')"
        throw
    }
}

