function Start-Scan {
    Write-Host "[SCAN] Scanning work..." -ForegroundColor Cyan
    $issues = Invoke-GH @("issue", "list", "--repo", $script:REPO, "--state", "open", "--json", "number,title,labels", "--limit", "20")
    Write-Host $issues
    
    if (![string]::IsNullOrWhiteSpace($script:PROJECT_NUMBER)) {
        Write-Host ""
        Write-Host "[PROJECT] Project items:" -ForegroundColor Cyan
        try { 
            $items = & gh project item-list $script:PROJECT_NUMBER --owner $script:REPO_OWNER --format json --limit 20 2>$null
            Write-Host $items
        } catch { }
    }
}

function Complete-Scan {
    Write-Host "[COMPLETE] Ready for completion..." -ForegroundColor Cyan
    $issues = Invoke-GH @("issue", "list", "--repo", $script:REPO, "--state", "open", "--json", "number,title", "--limit", "20")
    Write-Host $issues
    Write-Host ""
    Write-Host "Today: $(Get-Today)"
    Write-Host 'Close with: .\scripts\smart-ops.ps1 close [number]' -ForegroundColor Gray
}

function New-Issue {
    param(
        [string]$Title,
        [string]$Body = "",
        [string]$Labels = "enhancement",
        [int]$Days = 7
    )
    
    if ([string]::IsNullOrWhiteSpace($Title)) {
        Write-Err "Title required"
        return
    }
    
    Write-Host "[CREATE] Creating: $Title ($Days days)" -ForegroundColor Cyan
    
    $url = Invoke-GH @("issue", "create", "--repo", $script:REPO, "--title", $Title, "--body", $Body, "--label", $Labels)
    
    if ($url -match '/(\d+)$') {
        $num = $Matches[1]
        Write-Ok "Created #$num"
        
        if (![string]::IsNullOrWhiteSpace($script:PROJECT_ID)) {
            try {
                $itemId = & gh project item-add $script:PROJECT_NUMBER --owner $script:REPO_OWNER --url $url --format json --jq '.id'
                
                if (![string]::IsNullOrWhiteSpace($script:START_DATE_FIELD_ID)) {
                    & gh project item-edit --id $itemId --project-id $script:PROJECT_ID --field-id $script:START_DATE_FIELD_ID --date (Get-Today) 2>$null
                }
                if (![string]::IsNullOrWhiteSpace($script:TARGET_DATE_FIELD_ID)) {
                    & gh project item-edit --id $itemId --project-id $script:PROJECT_ID --field-id $script:TARGET_DATE_FIELD_ID --date (Get-FutureDate -Days $Days) 2>$null
                }
                Write-Ok "Added to project"
            } catch {
                Write-Err "Failed to add to project"
            }
        }
        Write-Host $url
    }
}

function Close-Issue {
    param([string]$Num, [string]$Comment = "Completed")
    
    if ([string]::IsNullOrWhiteSpace($Num)) {
        Write-Err "Issue number required"
        return
    }
    
    $confirm = Read-Host "Close #$Num ? (y/N)"
    if ($confirm -ne 'y') { return }
    
    Invoke-GH @("issue", "close", $Num, "--repo", $script:REPO, "--comment", $Comment)
    Write-Ok "Closed #$Num"
}

function Move-ToProgress {
    param([string]$Id)
    
    if ([string]::IsNullOrWhiteSpace($script:PROJECT_ID)) {
        Write-Err "No project configured"
        return
    }
    if ([string]::IsNullOrWhiteSpace($Id)) {
        Write-Err "Item ID required"
        return
    }
    
    & gh project item-edit --id $Id --field-id $script:STATUS_FIELD_ID --project-id $script:PROJECT_ID --single-select-option-id $script:IN_PROGRESS_OPTION_ID
    
    if (![string]::IsNullOrWhiteSpace($script:START_DATE_FIELD_ID)) {
        & gh project item-edit --id $Id --project-id $script:PROJECT_ID --field-id $script:START_DATE_FIELD_ID --date (Get-Today) 2>$null
    }
    Write-Ok "-> In Progress"
}

function Move-ToDone {
    param([string]$Id)
    
    if ([string]::IsNullOrWhiteSpace($script:PROJECT_ID)) {
        Write-Err "No project configured"
        return
    }
    if ([string]::IsNullOrWhiteSpace($Id)) {
        Write-Err "Item ID required"
        return
    }
    
    & gh project item-edit --id $Id --field-id $script:STATUS_FIELD_ID --project-id $script:PROJECT_ID --single-select-option-id $script:DONE_OPTION_ID
    Write-Ok "-> Done"
}

